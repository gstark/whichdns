const expect = std.testing.expect;

test "default server list has unique IPv4 UDP endpoints" {
    try std.testing.expectEqual(125, list.len);
    for (list, 0..) |server, i| {
        for (list[0..i]) |earlier| try expect(!std.mem.eql(u8, earlier.target, server.target));
    }
    try expect(std.mem.eql(u8, list[0].name, "Cloudflare"));
    try expect(std.mem.eql(u8, list[0].target, "1.0.0.1"));
    try std.testing.expectEqual(53, list[0].port);
    for (list) |server| {
        try expect(server.target.len > 0);
    }
}
